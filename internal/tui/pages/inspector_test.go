// TestInspectorWidthsNoOverflow: at 120/90/70 wide terminals every
// body line stays inside the content area and the body is exactly the
// content height on all four tabs.
func TestInspectorWidthsNoOverflow(t *testing.T) {
	t.Parallel()

	for _, w := range []int{120, 90, 70} {
		for _, tab := range []int{viewFields, viewBitmap, viewPacked, viewRawJSON} {
			in := inspPage(t, inspTreePurchase(), w, 30)
			cursorOn(t, in, "55")
			_, _ = in.Update(specialKey(tea.KeyRight))
			inspToTab(t, in, tab)

			_, ch := frame.ContentSize(w, 30)
			lines := strings.Split(in.View().Content, "\n")
			if len(lines) != ch {
				t.Fatalf("w=%d tab=%d: body %d lines, want %d", w, tab, len(lines), ch)
			}
			for i, ln := range lines {
				if n := cellWidth(ln); n > w {
					t.Fatalf("w=%d tab=%d line %d: %d cells > %d", w, tab, i, n, w)
				}
			}
		}
	}
}

// TestInspectorHintsAreWired: the §C hints name the page-local keys and
// keep tab/compose/back primary for the narrow footer.
func TestInspectorHintsAreWired(t *testing.T) {
	t.Parallel()

	in := NewInspector(asciiTheme(t))

	prim := map[string]bool{}
	all := map[string]bool{}
	for _, h := range in.Hints() {
		all[h.Key] = true
		if h.Primary {
			prim[h.Key] = true
		}
	}
	for _, k := range []string{"tab", "enter", "esc"} {
		if !prim[k] {
			t.Errorf("hint %s must be primary", k)
		}
	}
	for _, k := range []string{"j/k", "r"} {
		if !all[k] {
			t.Errorf("hint %s missing", k)
		}
	}
}

