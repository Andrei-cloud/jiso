// specialKey builds a named key press (arrows/enter) for page tests
// (Text stays empty: bubbles matches "enter" only on the bare code).
func specialKey(code rune) tea.KeyPressMsg { return tea.KeyPressMsg{Code: code} }

// enterKey is the Enter press as the terminal delivers it.
func enterKey() tea.KeyPressMsg { return specialKey('\r') }

// cellWidth is the printable cell width of a rendered line.
func cellWidth(s string) int { return lipgloss.Width(s) }
